/**
 * 构建后生成 dist/sw.js：预缓存全部产物 + 导航请求 network-first。
 * 无需 Workbox；纯手写约 60 行，行为可读、可控。
 */
import { createHash } from 'node:crypto'
import { readdir, readFile, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'

const DIST = path.resolve('dist')
const BASE = '/Mindmap/'
const VERSION = process.env.SW_VERSION ?? 'v1'

async function walk(dir, prefix = '') {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name
    if (entry.isDirectory()) out.push(...(await walk(path.join(dir, entry.name), rel)))
    else out.push(rel)
  }
  return out
}

async function main() {
  const files = (await walk(DIST)).filter((file) => file !== 'sw.js')
  const hash = createHash('sha256')
  for (const file of files.sort()) {
    const info = await stat(path.join(DIST, file))
    hash.update(`${file}:${info.size}`)
  }
  const stamp = `${VERSION}-${hash.digest('hex').slice(0, 10)}`
  const precache = files.map((file) => `${BASE}${file}`)

  const source = `/* generated by scripts/build-sw.mjs · ${stamp} */
const CACHE = 'mindmap-${stamp}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};
const BASE = ${JSON.stringify(BASE)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(async () => (await caches.match(request)) ?? (await caches.match(BASE)) ?? Response.error()),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok && response.type === 'basic') {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    }),
  );
});
`

  await writeFile(path.join(DIST, 'sw.js'), source, 'utf8')
  console.log(`已生成 dist/sw.js（${precache.length} 个预缓存文件，${stamp}）`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
